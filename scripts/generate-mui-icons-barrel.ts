import fs from "fs";
import path from "path";

const rootDir = path.resolve(__dirname, "..");
const muiIconsBarrelPath = path.join(rootDir, "wwwroot/app/vendor-react-mui-icons.generated.ts");

function collectMuiIconNames(): string[] {
    const iconRegex = /from\s+['"]@mui\/icons-material\/([A-Za-z0-9_]+)['"]/g;
    const icons = new Set<string>();
    const reactRoot = path.join(rootDir, "wwwroot/app/react");

    function walk(dir: string): void {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            const full = path.join(dir, entry.name);
            if (entry.isDirectory()) {
                walk(full);
            } else if (/\.(tsx?|jsx?)$/.test(entry.name)) {
                const content = fs.readFileSync(full, "utf8");
                let m: RegExpExecArray | null;
                while ((m = iconRegex.exec(content)) !== null) {
                    icons.add(m[1]);
                }
            }
        }
    }

    walk(reactRoot);
    return Array.from(icons).sort();
}

export function generateMuiIconsBarrel(): void {
    const icons = collectMuiIconNames();
    const lines = [
        "// AUTO-GENERATED by scripts/generate-mui-icons-barrel.ts — do not edit. Re-emitted on every build.",
        "// Lists every @mui/icons-material icon used under wwwroot/app/react so the",
        "// vendor-react bundle can expose them to module bundles via window.MUIIcons.",
        "",
        ...icons.map(name => `import ${name} from "@mui/icons-material/${name}";`),
        "",
        "export const MUIIcons = {",
        ...icons.map(name => `    ${name},`),
        "} as const;",
        "",
    ];
    const next = lines.join("\n");
    if (fs.existsSync(muiIconsBarrelPath)) {
        const current = fs.readFileSync(muiIconsBarrelPath, "utf8");
        if (current === next) return;
    }
    fs.writeFileSync(muiIconsBarrelPath, next);
}

const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(__filename);
if (invokedDirectly) {
    generateMuiIconsBarrel();
}
